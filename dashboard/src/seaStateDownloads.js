const safeName = (value) => String(value || "sea-state").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

function saveBlob(blob, filename) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  link.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

function periodLabel(result) {
  const start = result.time_start?.slice(0, 10) || result.source_manifest?.time_start?.slice(0, 10) || "unknown";
  const end = result.time_end?.slice(0, 10) || result.source_manifest?.time_end?.slice(0, 10) || "unknown";
  return `${start} to ${end}`;
}

export function spatialDescription(method, result) {
  if (method === "zone") {
    const f = result.filters || {};
    return `Zone: ${f.latitude_min}° to ${f.latitude_max}° latitude, ${f.longitude_min}° to ${f.longitude_max}° longitude`;
  }
  if (method === "location") {
    const s = result.spatial_selection || {};
    return `Requested point: ${s.requested?.latitude?.toFixed(4)}°, ${s.requested?.longitude?.toFixed(4)}° | ERA5 cell: ${s.matched?.latitude?.toFixed(4)}°, ${s.matched?.longitude?.toFixed(4)}° | offset ${s.distance_km?.toFixed(2)} km`;
  }
  const route = result.route || {};
  const first = route.coordinates?.[0] || [];
  const last = route.coordinates?.at(-1) || [];
  return `Route: ${first[1]?.toFixed(3)}°, ${first[0]?.toFixed(3)}° to ${last[1]?.toFixed(3)}°, ${last[0]?.toFixed(3)}° | ${route.length_nm?.toFixed(0)} nm | ${route.unique_grid_cells} ERA5 cells`;
}

function heatColor(value, maximum) {
  if (!(value > 0) || !(maximum > 0)) return "#edf4f6";
  const ratio = Math.min(1, Math.sqrt(value / maximum));
  return `hsl(188 ${35 + ratio * 36}% ${97 - ratio * 53}%)`;
}

export function downloadScatterPng(method, result) {
  const rows = result.hs_edges.length - 1;
  const columns = result.tp_edges.length - 1;
  const cellW = Math.max(54, Math.min(84, 1100 / columns));
  const cellH = 42;
  const left = 170;
  const top = 210;
  const width = Math.ceil(left + columns * cellW + 80);
  const height = Math.ceil(top + rows * cellH + 150);
  const scale = 2;
  const canvas = document.createElement("canvas");
  canvas.width = width * scale;
  canvas.height = height * scale;
  const ctx = canvas.getContext("2d");
  ctx.scale(scale, scale);
  ctx.fillStyle = "#07141d";
  ctx.fillRect(0, 0, width, height);
  ctx.fillStyle = "#f1f7f8";
  ctx.font = "700 27px Segoe UI, sans-serif";
  ctx.fillText("Hs–Tp Sea-State Scatter Diagram", 48, 50);
  ctx.fillStyle = "#6bdae0";
  ctx.font = "600 14px Segoe UI, sans-serif";
  ctx.fillText(`${method[0].toUpperCase()}${method.slice(1)} analysis`, 48, 80);
  ctx.fillStyle = "#b4c5cc";
  ctx.font = "13px Segoe UI, sans-serif";
  ctx.fillText(`Period: ${periodLabel(result)}`, 48, 110);
  ctx.fillText(spatialDescription(method, result), 48, 136);
  ctx.fillText(`Source: ${result.source_name} | Valid Hs–Tp pairs: ${result.valid_observations.toLocaleString()}`, 48, 162);
  const maximum = Math.max(...result.probabilities.flat(), 0);
  ctx.textAlign = "center";
  ctx.textBaseline = "middle";
  for (let displayRow = 0; displayRow < rows; displayRow += 1) {
    const hsIndex = rows - displayRow - 1;
    const y = top + displayRow * cellH;
    ctx.fillStyle = "#a9bdc6";
    ctx.font = "11px Segoe UI, sans-serif";
    ctx.fillText(`${result.hs_edges[hsIndex]}–${result.hs_edges[hsIndex + 1]}`, left - 46, y + cellH / 2);
    for (let tpIndex = 0; tpIndex < columns; tpIndex += 1) {
      const value = result.probabilities[hsIndex][tpIndex];
      const x = left + tpIndex * cellW;
      ctx.fillStyle = heatColor(value, maximum);
      ctx.fillRect(x, y, cellW, cellH);
      ctx.strokeStyle = "#76949f";
      ctx.strokeRect(x, y, cellW, cellH);
      ctx.fillStyle = value / (maximum || 1) > 0.5 ? "#fff" : "#173149";
      ctx.font = "10px Segoe UI, sans-serif";
      ctx.fillText(value >= 0.005 ? `${value.toFixed(value >= 10 ? 1 : 2)}%` : "0%", x + cellW / 2, y + cellH / 2);
    }
  }
  ctx.fillStyle = "#a9bdc6";
  ctx.font = "10px Segoe UI, sans-serif";
  for (let i = 0; i < columns; i += 1) ctx.fillText(`${result.tp_edges[i]}–${result.tp_edges[i + 1]}`, left + i * cellW + cellW / 2, top + rows * cellH + 18);
  ctx.font = "600 13px Segoe UI, sans-serif";
  ctx.fillText("Peak period, Tp [s]", left + columns * cellW / 2, top + rows * cellH + 52);
  ctx.save();
  ctx.translate(45, top + rows * cellH / 2);
  ctx.rotate(-Math.PI / 2);
  ctx.fillText("Significant wave height, Hs [m]", 0, 0);
  ctx.restore();
  ctx.textAlign = "left";
  ctx.fillStyle = "#76909b";
  ctx.font = "11px Segoe UI, sans-serif";
  ctx.fillText("Generated by Motion Analysis · probabilities normalized to 100%", 48, height - 30);
  canvas.toBlob((blob) => blob && saveBlob(blob, `${safeName(method)}-scatter-${safeName(periodLabel(result))}.png`), "image/png");
}

export function downloadRouteMapPng(container, result) {
  const svg = container?.querySelector("svg");
  if (!svg) return;
  const clone = svg.cloneNode(true);
  const style = document.createElementNS("http://www.w3.org/2000/svg", "style");
  style.textContent = `.world-ocean{fill:#071824}.world-graticule{stroke:#173340;stroke-width:.8}.world-land path{fill:#17313d;stroke:#456471;stroke-width:.45}.route-line{fill:none;stroke:#25d7e0;stroke-width:3}.route-grid-point{fill:#0a1b26;stroke:#fff;stroke-width:1.4}.route-terminal{stroke:#fff;stroke-width:2}.route-terminal.origin{fill:#10836e}.route-terminal.destination{fill:#cf6e2b}`;
  clone.prepend(style);
  const blob = new Blob([new XMLSerializer().serializeToString(clone)], { type: "image/svg+xml" });
  const image = new Image();
  const url = URL.createObjectURL(blob);
  image.onload = () => {
    const canvas = document.createElement("canvas");
    canvas.width = 1920;
    canvas.height = 1160;
    const ctx = canvas.getContext("2d");
    ctx.fillStyle = "#07141d"; ctx.fillRect(0, 0, canvas.width, canvas.height);
    ctx.fillStyle = "#f1f7f8"; ctx.font = "700 38px Segoe UI"; ctx.fillText("Route-Specific Sea-State Analysis", 70, 65);
    ctx.fillStyle = "#b4c5cc"; ctx.font = "21px Segoe UI"; ctx.fillText(`Period: ${periodLabel(result)}`, 70, 105); ctx.fillText(spatialDescription("route", result), 70, 140);
    ctx.drawImage(image, 70, 180, 1780, 890);
    ctx.fillStyle = "#76909b"; ctx.font = "17px Segoe UI"; ctx.fillText("SeaRoute visualization only—not for vessel navigation · Natural Earth public-domain basemap", 70, 1110);
    canvas.toBlob((output) => output && saveBlob(output, `route-map-${safeName(periodLabel(result))}.png`), "image/png");
    URL.revokeObjectURL(url);
  };
  image.src = url;
}

export function downloadRouteCellsCsv(result) {
  const rows = result.route?.grid_points || [];
  const header = ["latitude", "longitude", "route_samples", "route_percent"];
  const csv = [
    `# period,${periodLabel(result)}`,
    `# route_length_nm,${result.route?.length_nm}`,
    `# sample_spacing_nm,${result.route?.sample_spacing_nm}`,
    header.join(","),
    ...rows.map((point) => [point.latitude, point.longitude, point.route_samples, point.weight_percent].join(",")),
  ].join("\r\n");
  saveBlob(new Blob([csv], { type: "text/csv;charset=utf-8" }), `route-era5-cells-${safeName(periodLabel(result))}.csv`);
}
